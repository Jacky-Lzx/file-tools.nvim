local h = dofile("tests/helpers.lua")
local yazi = require("file_tools.yazi")
h.test("DDS payloads preserve commas and filter unrelated senders", function()
  local events = yazi.parse('rename,0,42,{"from":"/project/a,b","to":"/project/c,d"}', "42")
  h.eq({ { kind = "Rename", path = "/project/a,b", to = "/project/c,d" } }, events)
  h.eq({}, yazi.parse('rename,0,24,{"from":"/a","to":"/b"}', "42"))
  h.eq({}, yazi.parse('rename,0,42,{"from":"sftp://host/a","to":"/b"}', "42"))
  h.eq({}, yazi.parse("not,a,dds,message", "42"))
  h.eq({}, yazi.parse('rename,0,42,{"from":null,"to":"/b"}', "42"))
end)

h.test("move, bulk rename, delete and handshake", function()
  local events = yazi.parse('move,0,42,{"items":[{"from":"/a","to":"/b"}]}', "42")
  h.eq("Rename", events[1].kind)
  events = yazi.parse('bulk-rename,0,42,{"changes":{"/a":"/b"}}', "42")
  h.eq("/b", events[1].to)
  events = yazi.parse('trash,0,42,{"urls":["/a","/b"]}', "42")
  h.eq(2, #events)
  h.eq("Delete", events[1].kind)
  local _, ready = yazi.parse('hey,0,99,{"peers":{"42":{}}}', "42")
  assert(ready)
end)

h.test("missing executable leaves no session", function()
  require("file_tools").setup({ yazi = { command = "file-tools-no-such-executable" } })
  assert(not pcall(yazi.open))
  assert(not yazi.state())
end)
h.finish()
