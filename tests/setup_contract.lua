vim.opt.rtp:prepend(vim.fn.getcwd())
local plugin = require("file_tools")
local options = { tree = { width = 52 } }
local caller = vim.deepcopy(options)
plugin.setup(options)
assert(vim.deep_equal(caller, options), "setup mutated caller configuration")
local commands = vim.api.nvim_get_commands({})
local handlers = vim.api.nvim_get_autocmds({})
assert(not pcall(plugin.setup, false), "setup(false) must reject an invalid configuration type")
assert(vim.deep_equal(commands, vim.api.nvim_get_commands({})), "Invalid setup replaced commands")
assert(vim.deep_equal(handlers, vim.api.nvim_get_autocmds({})), "Invalid setup replaced handlers")
plugin.setup(caller)
assert(#vim.api.nvim_get_autocmds({}) == #handlers, "Repeated setup duplicated automatic handlers")
print("file-tools.nvim: setup input isolation, invalid configuration and registration lifetime passed")

local config = require("file_tools.config")
options.tree.width = 80
assert(config.options.tree.width == 52)
local configured = vim.deepcopy(config.options)
assert(not pcall(plugin.setup, { tree = { width = 1 } }))
assert(vim.deep_equal(configured, config.options))
plugin.open({ root = vim.fn.getcwd(), focus = false })
assert(require("file_tools.tree").state())
plugin.dispose()
plugin.dispose()
assert(not require("file_tools.tree").state())
assert(vim.fn.exists("#FileToolsTree") == 0 and vim.fn.exists("#FileToolsTheme") == 0)
assert(vim.deep_equal(config.options, config.defaults))
plugin.setup(caller)
plugin.open({ root = vim.fn.getcwd(), focus = false })
assert(vim.fn.exists("#FileToolsTree") == 1)
plugin.dispose()
